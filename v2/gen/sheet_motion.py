def spring(k, c):
    w = math.sqrt(k); z = c / (2 * w); wd = w * math.sqrt(1 - z * z)
    return lambda t: 1 - math.exp(-z * w * t) * (math.cos(wd * t) + z * w / wd * math.sin(wd * t)) if t > 0 else 0.0


def bezier(x1, y1, x2, y2):
    def f(x):
        if x <= 0: return 0.0
        if x >= 1: return 1.0
        lo, hi = 0.0, 1.0
        for _ in range(40):
            u = (lo + hi) / 2; bx = 3 * (1 - u) ** 2 * u * x1 + 3 * (1 - u) * u * u * x2 + u ** 3
            lo, hi = (u, hi) if bx < x else (lo, u)
        u = (lo + hi) / 2; return 3 * (1 - u) ** 2 * u * y1 + 3 * (1 - u) * u * u * y2 + u ** 3
    return f


CURVES = {'move': {'fn': spring(280.6, 27.14), 'ms': 760, 'spring': True}, 'pop': {'fn': spring(320, 18), 'ms': 700, 'spring': True},
          'fade': {'fn': bezier(0.33, 1, 0.68, 1), 'css': 'cubic-bezier(0.33, 1, 0.68, 1)'},
          'draw': {'fn': bezier(0.65, 0, 0.35, 1), 'css': 'cubic-bezier(0.65, 0, 0.35, 1)'}}


def css_linear(name, n=40):
    c = CURVES[name]; T = c['ms'] / 1000.0; pts = [c['fn'](T * i / n) for i in range(n + 1)]; pts[-1] = 1.0
    return 'linear(' + ', '.join('0' if p == 0 else '1' if p == 1 else ('%.4f' % p).rstrip('0').rstrip('.') for p in pts) + ')'


