#!/usr/bin/env python3
"""Occasion heroes with the 18 Nov icon animations (20 Nov 2026) -> ../build/occ_icons_<occasion>.jsx.

Each new comp is a duplicate of the existing occasion hero (so the swoosh, swoosh matte, title letters / gradient /
outline / shadow and all their keys stay exactly as they are in AE, hand edits included), with the old illustration,
its alpha matte, its rig and the 10 bits replaced by the matching icon comp nested as one precomp layer.
  AE: 01 Hero lotties (export these)/Occasion sets (icons 18 Nov)/<NN Label>/GR hero <screen> - <Occasion> · icons
Placement (scale, position) comes from fit_icons.py (../build/icon_fit/placement.json): SIFT + photometric fit of the icon
rest frame onto the old illustration rest frame. Timing: the icon comps start their entrance at 0.10 s, the frame the old
illustration rig started (both first visible at frame 7), so the precomp starts at 0 (OFFSET below), and every icon has
settled by 3.0 s and holds to the last frame. The precomp layer collapses transformations (AE draws the icon parts
straight into the hero, as lottie does) and rests at 0 deg; every part inside rests at 0.25 deg (icons builder).
Re-running updates the icon layer of comps it built earlier (placement / timing) and builds the missing ones; it never
touches the old heroes or the icon comps.  usage: gen_occ_icons.py [occasion ...]"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

ORDER = ['default', 'eid', 'birthday', 'babyshower', 'wedding', 'housewarming', 'anniversary', 'other']
LABEL = {'default': 'Default', 'eid': 'Eid', 'birthday': 'Birthday', 'babyshower': 'Baby shower', 'wedding': 'Wedding',
         'housewarming': 'House warming', 'anniversary': 'Anniversary', 'other': 'Other'}
SCREEN = {'p5': '1.1 Occasion', 'p3': '2.3 Whose is it', 'p6': 'Name your registry', 'p1': '1.3 When is it',
          'p4': '2.5 Due date', 'p2': '1.4 Delivery details'}
PG_ORDER = ['p5', 'p3', 'p6', 'p1', 'p4', 'p2']
OFFSET = 0.0          # precomp start time (s): icon entrance 0.10 s == old illustration entrance 0.10 s
SUFFIX = ' · icons'
BUILD = os.path.join(ROOT, 'build')
PL = json.load(open(os.path.join(BUILD, 'icon_fit', 'placement.json')))

TPL = r'''// Occasion heroes with the 18 Nov icon animations. Generated by occasions/gen/gen_occ_icons.py. ASCII only.
// Duplicates each old occasion hero, removes its illustration / alpha matte / rig / bits from the DUPLICATE, nests the
// icon comp in their place. Never edits the old heroes or the icon comps, never saves.
var SPEC = /*SPEC*/null;
var TAG = "gr-hero-icons";
var NL = String.fromCharCode(10);
var LOG = new File(SPEC.log); LOG.encoding = "UTF-8"; LOG.open("w"); LOG.close();
function w(s) { LOG.open("a"); LOG.write(s + NL); LOG.close(); }
function findIn(name, cls, parent) {
  for (var i = 1; i <= app.project.numItems; i++) { var it = app.project.item(i);
    if (it.name === name && it instanceof cls && (!parent || it.parentFolder === parent)) return it; }
  return null;
}
function folder(name, parent) {
  var f = findIn(name, FolderItem, parent);
  if (!f) { f = app.project.items.addFolder(name); f.parentFolder = parent; }
  return f;
}
function tr(L, mn) { return L.property("ADBE Transform Group").property(mn); }
function placeIcon(L, C) {
  L.collapseTransformation = true;
  L.startTime = C.offset; L.inPoint = 0; L.outPoint = L.containingComp.duration;
  tr(L, "ADBE Anchor Point").setValue([300, 300]);
  tr(L, "ADBE Position").setValue(C.pos);
  tr(L, "ADBE Scale").setValue([C.scale, C.scale]);
  tr(L, "ADBE Rotate Z").setValue(0);
  tr(L, "ADBE Opacity").setValue(100);
}
function build(C, rootF) {
  var srcF = findIn(SPEC.src_root, FolderItem, rootF), dstF = folder(SPEC.dst_root, rootF);
  var sf = findIn(C.folder, FolderItem, srcF); if (!sf) return C.dst + ": ERROR no source folder " + C.folder;
  var src = findIn(C.src, CompItem, sf); if (!src) return C.dst + ": ERROR no source comp " + C.src;
  var icon = findIn(C.icon, CompItem, findIn(SPEC.icon_root, FolderItem, app.project.rootFolder)); if (!icon) return C.dst + ": ERROR no icon comp " + C.icon;
  var df = folder(C.folder, dstF);
  var comp = findIn(C.dst, CompItem, df), L, i;
  if (comp) {
    if (comp.comment.indexOf(TAG) !== 0) return C.dst + ": exists without tag, left alone";
    L = comp.layer(SPEC.icon_layer_prefix + C.icon + ")"); if (!L) return C.dst + ": ERROR icon layer missing";
    placeIcon(L, C); return C.dst + ": updated icon layer";
  }
  comp = src.duplicate(); comp.name = C.dst; comp.parentFolder = df;
  comp.comment = TAG + " | from " + C.src + " | icon " + C.icon;
  // remove the old illustration from the duplicate: matte child first, then the picture, the rig, the bits
  var kill = [];
  for (i = 1; i <= comp.numLayers; i++) { var n = comp.layer(i).name;
    if (n === "illustration alpha (matte)" || n === "illustration" || n === "illustration rig" || n.indexOf("bit ") === 0) kill.push(n); }
  var order = ["illustration alpha (matte)", "illustration", "illustration rig"];
  for (i = 0; i < order.length; i++) if (comp.layer(order[i])) comp.layer(order[i]).remove();
  for (i = comp.numLayers; i >= 1; i--) if (comp.layer(i).name.indexOf("bit ") === 0) comp.layer(i).remove();
  L = comp.layers.add(icon); L.name = SPEC.icon_layer_prefix + C.icon + ")"; L.comment = TAG;
  L.moveBefore(comp.layer("swoosh draw (matte)"));
  placeIcon(L, C);
  var names = []; for (i = 1; i <= comp.numLayers; i++) names.push(comp.layer(i).name);
  comp.time = comp.duration - comp.frameDuration;
  return C.dst + ": built (removed " + kill.length + ") -> " + names.join(" / ");
}
var RESULT = [];
try {
  var rootF = findIn(SPEC.root, FolderItem, app.project.rootFolder);
  for (var p = 0; p < SPEC.comps.length; p++) { var r = build(SPEC.comps[p], rootF); RESULT.push(r); w(r); }
} catch (err) { RESULT.push("ERROR line " + err.line + ": " + err.toString()); w(RESULT[RESULT.length - 1]); }
RESULT.join(NL);
'''

only = sys.argv[1:]
for i, occ in enumerate(ORDER):
    if only and occ not in only: continue
    comps = []
    for pg in PG_ORDER:
        if not os.path.exists(os.path.join(ROOT, 'art', occ, pg, 'hero.json')): continue
        P = PL[SCREEN[pg]]
        src = 'GR hero %s - %s' % (SCREEN[pg], LABEL[occ])
        comps.append({'src': src, 'dst': src + SUFFIX, 'folder': '%02d %s' % (i, LABEL[occ]), 'icon': P['icon_comp'],
                      'pos': P['pos'], 'scale': P['scale'], 'offset': OFFSET})
    S = {'comps': comps, 'root': '01 Hero lotties (export these)', 'src_root': 'Occasion sets', 'dst_root': 'Occasion sets (icons 18 Nov)',
         'icon_root': '05 Icon lotties (18 Nov asset pack)', 'icon_layer_prefix': 'icon (', 'log': os.path.join(BUILD, 'occ_icons_%s.log' % occ)}
    out = os.path.join(BUILD, 'occ_icons_%s.jsx' % occ)
    open(out, 'w').write(TPL.replace('/*SPEC*/null', json.dumps(S, ensure_ascii=True)))
    print('%-13s %d comps -> %s' % (occ, len(comps), os.path.basename(out)))
