#!/usr/bin/env python3
"""Gift Registry bottom sheet: ONE motion source for the AE preview comp, the web proto (CSS) and the spec.

    python3 sheet_motion.py   ->  build/build_sheet.jsx, proto/motion.css, proto/motion.json

Screen 375x812 pt (Figma 2:33354). Times in ms from the tap that opens the sheet.
Curves (noon-motion + nano house style):
  MOVE   spring stiffness 280.6, damping 27.14 (noon standard Spring(300, 28)), 760 ms   sheet, text rise, button rise
  POP    spring stiffness 320,   damping 18    (nano pop, ~13 % overshoot),     700 ms   numbers, icons
  FADE   cubic-bezier(0.33, 1, 0.68, 1)  (noon fade-in)                                  scrim, opacities
  DRAW   cubic-bezier(0.65, 0, 0.35, 1)  (noon ease-in-out)                              dotted separators
"""
import json, math, os

HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
BUILD = os.path.join(ROOT, 'build'); PROTO = os.path.join(ROOT, 'proto'); SHEET = os.path.join(ROOT, 'figma', 'sheet')
os.makedirs(BUILD, exist_ok=True); os.makedirs(PROTO, exist_ok=True)


def spring(k, c):
    w = math.sqrt(k); z = c / (2 * w); wd = w * math.sqrt(max(1e-9, 1 - z * z))
    return lambda t: 1 - math.exp(-z * w * t) * (math.cos(wd * t) + z * w / wd * math.sin(wd * t)) if t > 0 else 0.0


def bezier(x1, y1, x2, y2):
    def f(x):
        if x <= 0: return 0.0
        if x >= 1: return 1.0
        lo, hi = 0.0, 1.0
        for _ in range(40):
            u = (lo + hi) / 2; bx = 3 * (1 - u) ** 2 * u * x1 + 3 * (1 - u) * u * u * x2 + u ** 3
            lo, hi = (u, hi) if bx < x else (lo, u)
        u = (lo + hi) / 2; return 3 * (1 - u) ** 2 * u * y1 + 3 * (1 - u) * u * u * y2 + u ** 3
    return f


CURVES = {
    'move': {'fn': spring(280.6, 27.14), 'ms': 760, 'css': None, 'label': 'SPRING(stiffness 280.6, damping 27.14)'},
    'pop':  {'fn': spring(320, 18), 'ms': 700, 'css': None, 'label': 'SPRING(stiffness 320, damping 18)'},
    'fade': {'fn': None, 'ms': None, 'css': 'cubic-bezier(0.33, 1, 0.68, 1)', 'bz': (0.33, 1, 0.68, 1)},
    'draw': {'fn': None, 'ms': None, 'css': 'cubic-bezier(0.65, 0, 0.35, 1)', 'bz': (0.65, 0, 0.35, 1)},
}
for c in CURVES.values():
    if c['fn'] is None: c['fn'] = bezier(*c['bz'])


def ease(name, dur_ms):
    c = CURVES[name]
    if c['css'] is None:                       # springs run on their own clock, dur is the settle window
        return lambda x: c['fn'](x * c['ms'] / 1000.0)
    return c['fn']


def css_linear(name, n=40):
    c = CURVES[name]; T = c['ms'] / 1000.0
    pts = [c['fn'](T * i / n) for i in range(n + 1)]; pts[-1] = 1.0
    return 'linear(' + ', '.join(('%.4f' % p).rstrip('0').rstrip('.') if p not in (0, 1) else str(int(p)) for p in pts) + ')'


# ---- choreography (ms) ----
T_SHEET = 0            # sheet + scrim start with the tap
T_LOTTIE = 120         # hero lottie starts when the sheet is ~70 % up (holds frame 0 while it travels)
LOTTIE_MS = 3400
T_ROWS, ROW_STAGGER = 760, 100
T_BTN = 1080
SHEET_DY = 560         # pt below its rest (card top 296 -> 856, off the 812 screen)

rows = []
for i in range(3):
    t = T_ROWS + i * ROW_STAGGER
    rows.append({'num': {'t': t, 'curve': 'pop', 'scale': [0, 1]},
                 'text': {'t': t + 40, 'curve': 'move', 'dy': 8, 'fade': 320},
                 'icon': {'t': t + 90, 'curve': 'pop', 'scale': [0.4, 1], 'fade': 120},
                 'sep': ({'t': t + 120, 'curve': 'draw', 'ms': 420} if i < 2 else None)})
motion = {
    'screen': [375, 812], 'curves': {k: {'css': (v['css'] or css_linear(k)), 'ms': v['ms'], 'label': v.get('label')} for k, v in CURVES.items()},
    'scrim': {'t': T_SHEET, 'ms': 520, 'curve': 'fade', 'to': 0.8},
    'sheet': {'t': T_SHEET, 'curve': 'move', 'dy': SHEET_DY},
    'homeInd': {'t': T_SHEET, 'ms': 200, 'curve': 'lin'},
    'lottie': {'t': T_LOTTIE, 'ms': LOTTIE_MS, 'file': 'lottie/gift-hero-nobg.json', 'frames': 204, 'fps': 60},
    'rows': rows,
    'button': {'t': T_BTN, 'curve': 'move', 'dy': 16, 'fade': 320},
}
json.dump(motion, open(os.path.join(PROTO, 'motion.json'), 'w'), indent=1)
open(os.path.join(PROTO, 'motion.js'), 'w').write('// generated by gen/sheet_motion.py\nwindow.MOTION = ' + json.dumps(motion) + ';\n')

css = [':root {', '  /* generated by gen/sheet_motion.py: do not edit by hand */']
for k in ('move', 'pop'):
    css.append('  --%s: %s;' % (k, css_linear(k)))
    css.append('  --%s-ms: %dms;' % (k, CURVES[k]['ms']))
css += ['  --fade: %s;' % CURVES['fade']['css'], '  --draw: %s;' % CURVES['draw']['css'], '}']
open(os.path.join(PROTO, 'motion.css'), 'w').write('\n'.join(css) + '\n')

def rounded_top(src, dst, r):
    """The static hero bg for the AE preview, with the card's rounded top corners cut out (the proto clips by CSS)."""
    from PIL import ImageDraw
    im = Image.open(src).convert('RGBA'); w, h = im.size
    m = Image.new('L', (w * 4, h * 4), 0); d = ImageDraw.Draw(m)
    d.rounded_rectangle([0, 0, w * 4 - 1, (h + r) * 4], radius=r * 4, fill=255)      # bottom corners pushed off the picture
    im.putalpha(m.resize((w, h), Image.LANCZOS)); im.save(dst, optimize=True)
    return dst


# ---- AE preview: per-frame keys (2x, 60 fps) ----
FPS = 60; S = 2; DUR = 4.0


def track(t0_ms, curve, v0, v1, ms=None, fade=False):
    """[[t, v], ...] one key per frame from t0 to settle; v0/v1 numbers or lists."""
    c = CURVES[curve]; span = (ms or c['ms']) / 1000.0
    f = (lambda x: x) if curve == 'lin' else (c['fn'] if c['css'] is not None else None)
    out = []
    n = int(round(span * FPS))
    for i in range(n + 1):
        tt = i / FPS
        x = (c['fn'](tt) if c['css'] is None else c['fn'](tt / span))
        if i == n: x = 1.0
        v = [a + (b - a) * x for a, b in zip(v0, v1)] if isinstance(v0, list) else v0 + (v1 - v0) * x
        out.append([round(t0_ms / 1000.0 + tt, 5), [round(q, 3) for q in v] if isinstance(v, list) else round(v, 3)])
    return out


def lin(t0_ms, ms, v0, v1):
    n = max(1, int(round(ms / 1000.0 * FPS)))
    return [[round(t0_ms / 1000.0 + i / FPS, 5), round(v0 + (v1 - v0) * i / n, 3)] for i in range(n + 1)]


def fadek(t0_ms, ms, v0=0, v1=100):
    f = CURVES['fade']['fn']; n = max(1, int(round(ms / 1000.0 * FPS)))
    return [[round(t0_ms / 1000.0 + i / FPS, 5), round(v0 + (v1 - v0) * f(i / n), 3)] for i in range(n + 1)]


def rb(name):   # Figma render bounds (screen pt) of the exported pieces
    return {'num1': [20.85, 484.86], 'num2': [19.92, 561.64], 'num3': [20.68, 634.76],
            'txt1': [72, 484], 'txt2': [72, 559], 'txt3': [72, 634],
            'ico1': [299, 483], 'ico2': [299, 559], 'ico3': [299, 633], 'btn': [17, 704]}[name]


