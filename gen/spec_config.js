/* ═══ PROJECT CONFIG — everything specific to this prototype lives here ═══════════
   The engine below never changes between projects: it reads window.SPEC only.
   Every timing comes from /motion.js (window.MOTION), generated by gen/sheet_motion.py — the same source that
   keys the After Effects preview comp, so the spec, the prototype and the video can't drift apart. */
window.SPEC = (() => {
  const { springFn, firstT, S, C, H, rowEnd, sceneEnd, sampleLen, wait: realWait } = SpecKit;
  const M = window.MOTION;

  const PATHS = { 1: '/' };
  const ITER = { 1: 'Iteration 01 · sheet rises, hero lottie, rows cascade, CTA rises' };

  const bezFn = (a, b, c, d) => {
    const cx = 3 * a, bx = 3 * (c - a) - cx, ax = 1 - cx - bx, cy = 3 * b, by = 3 * (d - b) - cy, ay = 1 - cy - by;
    const X = (t) => ((ax * t + bx) * t + cx) * t, Y = (t) => ((ay * t + by) * t + cy) * t;
    return (x) => { if (x <= 0) return 0; if (x >= 1) return 1; let lo = 0, hi = 1, t = x; for (let i = 0; i < 40; i++) { const v = X(t); if (Math.abs(v - x) < 1e-7) break; if (v < x) lo = t; else hi = t; t = (lo + hi) / 2; } return Y(t); };
  };
  const bezLin = (a, b, c, d, n = 20) => { const f = bezFn(a, b, c, d); return 'linear(' + Array.from({ length: n + 1 }, (_, i) => +f(i / n).toFixed(4)).join(', ') + ')'; };

  /* springs (ω = √stiffness, ζ = damping / 2√stiffness, mass 1) — motion.css --move / --pop */
  const SPR = {
    move: { name: 'MOVE spring', w: Math.sqrt(280.6), z: 27.14 / (2 * Math.sqrt(280.6)), src: 'motion.css --move: noon Spring(300, 28) = stiffness 280.6, damping 27.14, 760 ms, ~1.3% overshoot' },
    pop: { name: 'POP spring', w: Math.sqrt(320), z: 18 / (2 * Math.sqrt(320)), src: 'motion.css --pop: stiffness 320, damping 18 (nano pop), 700 ms, ~16% overshoot' },
  };
  const CURVE = {
    fadeIn: { name: 'Fade-in (--fade)', fn: bezLin(0.33, 1, 0.68, 1) },
    io: { name: 'Ease-in-out (--draw)', fn: bezLin(0.65, 0, 0.35, 1) },
    ios: { name: 'iOS sheet (--ios)', fn: bezLin(0.32, 0.72, 0, 1) },
    lin: { name: 'Linear', fn: 'linear(0, 1)' },
  };

  const MOVE_MS = M.curves.move.ms, POP_MS = M.curves.pop.ms;
  const CLOSE_MS = 360, SCRIM_OUT = 280, RESET_AT = 420;
  const L = M.lottie, LAST_F = L.frames - 1;

  const ROW_NAMES = ['Create & add items you want', 'Share it with your family & friends', 'Track your gifts as they come'];
  const rowRows = M.rows.flatMap((r, i) => {
    const k = i + 1, n = `Row ${k}`;
    const out = [
      { grp: `${n} · ${ROW_NAMES[i]} @ ${r.num.t}ms`, at: r.num.t, note: i === 0 ? `Rows cascade top to bottom, ${M.rows[1].num.t - r.num.t}ms apart, starting as the hero title finishes popping. In each row the number pops, the copy rises 40ms later, the illustration pops 90ms after the number, and the dotted line under it draws 120ms after the number.` : `${M.rows[1].num.t - M.rows[0].num.t}ms after row ${i}.` },
      { icon: 'scale', prop: 'Scale', layer: `${n} number`, sel: `.r${k} .num`, delay: r.num.t, dur: POP_MS, from: '0%', to: '100%', ease: S('pop'), note: `“0${k}” (Noontree ExtraBold, gradient + white outline, exported picture) pops from its centre with ~16% overshoot.` },
      { icon: 'opacity', prop: 'Opacity', layer: `${n} copy`, sel: `.r${k} .txt`, delay: r.text.t, dur: r.text.fade, from: '0', to: '1', ease: C('fadeIn') },
      { icon: 'move', prop: 'Move Y', layer: `${n} copy`, sel: `.r${k} .txt`, delay: r.text.t, dur: MOVE_MS, from: `${r.text.dy}px`, to: '0px', ease: S('move'), note: 'Title (Noontree SemiBold 14/20 #1D2539) and subtitle (Medium 12/18 #666D85) rise together as one block.' },
      { icon: 'scale', prop: 'Scale', layer: `${n} illustration`, sel: `.r${k} .ico`, delay: r.icon.t, dur: POP_MS, from: `${r.icon.scale[0] * 100}%`, to: '100%', ease: S('pop'), note: 'The 44×44 illustration pops from its centre.' },
      { icon: 'opacity', prop: 'Opacity', layer: `${n} illustration`, sel: `.r${k} .ico`, delay: r.icon.t, dur: r.icon.fade, from: '0', to: '1', ease: C('fadeIn') },
    ];
    if (r.sep) out.push({ icon: 'size', prop: 'Scale X', layer: `Separator ${k}`, sel: `.s${k}`, delay: r.sep.t, dur: r.sep.ms, from: '0%', to: '100%', ease: C('io'), note: 'The dotted divider (1pt, dash 0.5 / gap 3, round caps, #02060C at 15%) draws from left to right.' });
    return out;
  });

  const SCENES = [
    { id: 0, name: 'Overview', trig: 'the full journey, played end to end', summary: 'Sheet opens → hero lottie → rows cascade → CTA → sheet closes', overview: true },
    { id: 1, name: 'Sheet opens', trig: 'Tap the screen (also fires 600ms after the first load)', rows: () => [
      { icon: 'opacity', prop: 'Opacity', layer: 'Overlay', sel: '#scrim', delay: M.scrim.t, dur: M.scrim.ms, from: '0', to: '1', ease: C('fadeIn'), note: 'The 80% black overlay (Figma 2:34252) fades in under the sheet.' },
      { icon: 'move', prop: 'Move Y', layer: 'Gift Registry bottomsheet', sel: '#sheetWrap', delay: M.sheet.t, dur: MOVE_MS, from: `${M.sheet.dy}px`, to: '0px', ease: S('move'),
        note: 'The floating white card (351×478, radius 24, 12pt side margins) and its grabber rise from below the screen on the noon MOVE spring.' },
      { icon: 'opacity', prop: 'Opacity', layer: 'Home Indicator', sel: '.home-ind', delay: M.homeInd.t, dur: M.homeInd.ms, from: '0', to: '1', ease: C('lin') },
      { grp: `Hero lottie @ ${L.t}ms`, at: L.t, note: `Starts ${L.t}ms after the tap, while the sheet is ~70% up; until then it holds frame 0 (empty: the box, stars and title start at scale 0). The pink background behind it is a static picture drawn by the app (Figma 2:34284), the lottie has no background.` },
      { icon: 'flag', prop: 'Lottie · play once', layer: 'gifting (no bg)', sel: '#hero', delay: L.t, dur: L.ms, from: '0', to: `${LAST_F}`, ease: C('lin'),
        note: `gift-hero-nobg.json · 1053×516 comp (3x) shown at 351×172 at the top of the card, ${L.frames} frames @ ${L.fps} fps, played once and held on the last frame (= the Figma still). Inside: gift box springs up from its base (f6), swoosh draws behind it (f22), stars spin in (f29, f38), “Gift Registry” letters pop from the baseline 17ms apart (f35), box floats 6px and stars twinkle once, all at rest by f180.` },
      ...rowRows,
      { grp: `CTA @ ${M.button.t}ms`, at: M.button.t, note: 'The button arrives last, once the third row is underway.' },
      { icon: 'opacity', prop: 'Opacity', layer: 'Create Gift Registry', sel: '#cta', delay: M.button.t, dur: M.button.fade, from: '0', to: '1', ease: C('fadeIn') },
      { icon: 'move', prop: 'Move Y', layer: 'Create Gift Registry', sel: '#cta', delay: M.button.t, dur: MOVE_MS, from: `${M.button.dy}px`, to: '0px', ease: S('move'), note: 'nano button · Continue (radial #FF578F → #000, radius 16, shadow 0/1/7 at 15%) rises 16px.' },
    ] },
    { id: 2, name: 'Sheet closes', trig: 'Tap the overlay', rows: () => [
      { icon: 'opacity', prop: 'Opacity', layer: 'Overlay', sel: '#scrim', delay: 0, dur: SCRIM_OUT, from: '1', to: '0', ease: C('ios'), note: 'The overlay fades out faster than it came in.' },
      { icon: 'move', prop: 'Move Y', layer: 'Gift Registry bottomsheet', sel: '#sheetWrap', delay: 0, dur: CLOSE_MS, from: '0px', to: `${M.sheet.dy}px`, ease: C('ios'), note: 'The sheet drops off screen on the iOS sheet curve, with no spring on the way out and no content exit animation.' },
      { icon: 'opacity', prop: 'Opacity', layer: 'Home Indicator', sel: '.home-ind', delay: 0, dur: 200, from: '1', to: '0', ease: C('lin') },
      { icon: 'flag', prop: 'Reset', layer: 'gifting (no bg)', sel: '#hero', delay: RESET_AT, dur: 0, from: '—', to: '—', ease: C('lin'), note: 'Once off screen the lottie pauses and the rows reset, so the next open replays everything from frame 0.' },
    ] },
  ];

  function overview(v) {
    const at = { 1: 0, 2: L.t + L.ms + 600 };   // let the hero finish and rest before closing
    const rows = [1, 2].map((id) => ({ icon: 'flag', prop: `${id}`, layer: SCENES[id].name, sel: null, delay: at[id], dur: sceneEnd(SCENES[id].rows(v)), scene: id, from: '', to: '', ease: { kind: 'scene' }, note: `${SCENES[id].trig}.` }));
    const beats = [1, 2].map((id) => ({ at: at[id], fire: (d, w) => FIRE[id](d, w) }));
    return { rows, beats };
  }

  const ST = {
    async ready(d, w, e) {
      for (let i = 0; i < 100; i++) { if (w.proto && w.proto.ready()) break; await realWait(100); }
      await realWait(150);
      await e.advanceTo(e.vt + 100, 48);
    },
    async opened(d, w, e) {
      await ST.ready(d, w, e);
      d.getElementById('hot').click();
      await e.advanceTo(e.vt + L.t + L.ms + 300, 16);
    },
  };
  const PREP = { 0: 'ready', 1: 'ready', 2: 'opened' };
  const FIRE = {
    1: (d) => d.getElementById('hot').click(),
    2: (d) => d.getElementById('scrim').click(),
  };

  return {
    title: 'Gift Registry sheet — Animation Spec', device: { w: 375, h: 812, label: 'Custom (375x812 @3x)' },
    paths: PATHS, iterations: ITER, springs: SPR, curves: CURVE, scenes: SCENES, overview, states: ST, prep: PREP, fire: FIRE,
    assets: [
      { name: 'Gift Registry hero · no bg', file: '/lottie/gift-hero-nobg.json', download: 'gift-hero-nobg.json', preview: '/lottie/gift-hero-nobg.json', bg: '#ffb3cc', iters: [1] },
      { name: 'Gift Registry hero · with bg', file: '/lottie/gift-hero.json', download: 'gift-hero.json', preview: '/lottie/gift-hero.json', bg: '#ffffff', iters: [1] },
    ],
  };
})();
